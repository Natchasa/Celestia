def generate_timeless_bullets(hx, hn):
    x = HOUSE_CONCRETE[hx]
    n = HOUSE_CONCRETE[hn]
    bullets = []
    
    topic_x = x['topic']
    health_x = x['health']
    image_x = x['image']
    action_x = x['action']
    summary_x = x['summary']
    
    topic_n = n['topic']
    health_n = n['health']
    image_n = n['image']
    action_n = n['action']
    summary_n = n['summary']
    
    if hx == hn:
        bullets.append(f'เรื่อง{topic_x}มีความเข้มข้นและโดดเด่นเป็นพิเศษ ควรลงมือทำเรื่องนี้อย่างจริงจัง')
        bullets.append(f'เน้นการใส่ใจ{health_x} และวางแผนจัดการด้วยตนเอง')
        bullets.append(f'{image_x}มีความโดดเด่นชัดเจน และได้รับความสนใจจากคนรอบข้าง')
        bullets.append(f'เหมาะสำหรับการตัดสินใจเรื่อง{action_x} ด้วยตนเองอย่างเด็ดขาด')
        bullets.append(f'เน้น{summary_x} ให้ลงตัวและมั่นคงยิ่งขึ้น')
    else:
        bullets.append(f'ความตั้งใจในเรื่อง{topic_x} เป็นพลังสำคัญในการขับเคลื่อนเรื่อง{topic_n}')
        bullets.append(f'{health_x} ส่งผลโดยตรงต่อ{health_n}')
        bullets.append(f'{image_x} มีผลอย่างมากต่อ{image_n}')
        bullets.append(f'นำประสบการณ์เรื่อง{action_x} มาปรับใช้กับการจัดการเรื่อง{action_n}')
        bullets.append(f'{summary_x} ช่วยส่งเสริมและสร้างผลดีต่อ{summary_n}')
        
    return ' || '.join(bullets)

